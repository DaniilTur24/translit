import AppKit
import Carbon.HIToolbox

/// Replaces the current selection in the frontmost app with `transform(selection)`.
///
/// Works through the clipboard (Cmd+C, Cmd+V) because that is the only approach that behaves
/// the same in browsers, Electron apps, Telegram and native fields. The user's clipboard is
/// snapshotted (every item, every type) and put back afterwards. Nothing is logged or stored.
final class SelectionReplacer {
    private let queue = DispatchQueue(label: "translit.replace")
    private var busy = false   // touched on the main thread only

    /// Time the target app gets to process the paste before the clipboard is restored.
    private let pasteSettleTime: useconds_t = 300_000

    func run(_ transform: @escaping (String) -> String) {
        guard !busy else { return }
        busy = true
        queue.async {
            self.perform(transform)
            DispatchQueue.main.async { self.busy = false }
        }
    }

    private func perform(_ transform: (String) -> String) {
        guard AXIsProcessTrusted() else {
            requestAccessibility()
            beep()
            return
        }
        // Password fields: Carbon secure input is on, or the focused element says it is secure.
        guard !IsSecureEventInputEnabled(), !focusedFieldIsSecure() else {
            beep()
            return
        }

        waitForModifierRelease(timeout: 0.8)

        let pb = NSPasteboard.general
        let saved = Snapshot(pb)
        let countBefore = pb.changeCount

        postKey(CGKeyCode(kVK_ANSI_C))
        // Nothing selected -> the app copies nothing -> clipboard is untouched, nothing to restore.
        guard waitForChange(pb, since: countBefore, timeout: 0.5) else { return }
        usleep(30_000)

        guard let selected = pb.string(forType: .string), !selected.isEmpty else {
            saved.restore(to: pb)
            return
        }
        let converted = transform(selected)
        guard converted != selected else {
            saved.restore(to: pb)
            return
        }

        let item = NSPasteboardItem()
        item.setString(converted, forType: .string)
        // Ask clipboard managers not to record this temporary value.
        for type in ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
            item.setData(Data(), forType: NSPasteboard.PasteboardType(type))
        }
        pb.clearContents()
        pb.writeObjects([item])

        postKey(CGKeyCode(kVK_ANSI_V))
        usleep(pasteSettleTime)
        saved.restore(to: pb)
    }

    // MARK: - Safety

    private func focusedFieldIsSecure() -> Bool {
        let system = AXUIElementCreateSystemWide()
        var focused: CFTypeRef?
        guard AXUIElementCopyAttributeValue(system, kAXFocusedUIElementAttribute as CFString, &focused) == .success,
              let element = focused else { return false }
        var subrole: CFTypeRef?
        AXUIElementCopyAttributeValue(element as! AXUIElement, kAXSubroleAttribute as CFString, &subrole)
        return (subrole as? String) == "AXSecureTextField"
    }

    private func requestAccessibility() {
        // Shows the system prompt that leads to Privacy & Security > Accessibility.
        _ = AXIsProcessTrustedWithOptions(["AXTrustedCheckOptionPrompt": true] as CFDictionary)
    }

    private func beep() {
        DispatchQueue.main.async { NSSound.beep() }
    }

    // MARK: - Keyboard

    /// The hotkey's own modifiers are still held when it fires; wait so Cmd+C is not seen as Ctrl+Opt+Cmd+C.
    private func waitForModifierRelease(timeout: TimeInterval) {
        let mask: CGEventFlags = [.maskControl, .maskAlternate, .maskShift, .maskCommand]
        let deadline = Date().addingTimeInterval(timeout)
        while !CGEventSource.flagsState(.combinedSessionState).intersection(mask).isEmpty, Date() < deadline {
            usleep(10_000)
        }
    }

    /// Cmd+<key>. Key codes are physical positions, so C and V are the same on QWERTZ.
    private func postKey(_ key: CGKeyCode) {
        let source = CGEventSource(stateID: .privateState)
        for down in [true, false] {
            let event = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: down)
            event?.flags = .maskCommand
            event?.post(tap: .cghidEventTap)
            usleep(10_000)
        }
    }

    private func waitForChange(_ pb: NSPasteboard, since count: Int, timeout: TimeInterval) -> Bool {
        let deadline = Date().addingTimeInterval(timeout)
        while Date() < deadline {
            if pb.changeCount != count { return true }
            usleep(10_000)
        }
        return pb.changeCount != count
    }

    // MARK: - Clipboard

    /// Full copy of the clipboard: every item with every type, so images, files and rich text survive.
    private struct Snapshot {
        private let items: [[(NSPasteboard.PasteboardType, Data)]]

        init(_ pb: NSPasteboard) {
            items = (pb.pasteboardItems ?? []).map { item in
                item.types.compactMap { type in item.data(forType: type).map { (type, $0) } }
            }
        }

        func restore(to pb: NSPasteboard) {
            pb.clearContents()
            let restored = items.map { pairs -> NSPasteboardItem in
                let item = NSPasteboardItem()
                for (type, data) in pairs { item.setData(data, forType: type) }
                return item
            }
            if !restored.isEmpty { pb.writeObjects(restored) }
        }
    }
}
